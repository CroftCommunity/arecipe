// Phase 5b build tool (plans/2026-08-12-1): mine the census's "X or Y" lines
// into src/recipes/substitutions-mined.json (a second curated source of
// suggestions beside the reference chart) and print a review report to
// runs/ingredient-normalization/ALTERNATIVES.md. Same shape as
// build-ingredientkeys.mjs: the logic is the TS core (alternatives-mine.ts),
// bundled here with esbuild so the mining reads lines exactly as the app does.
//
//   node scripts/mine-alternatives.mjs            # write + report
//   node scripts/mine-alternatives.mjs --dry-run  # report only
//   --min-lines N   line floor for a pair (default 3)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';

const args = process.argv.slice(2);
const DRY = args.includes('--dry-run');
const MIN_LINES = Number(args.includes('--min-lines') ? args[args.indexOf('--min-lines') + 1] : '3');
const OUT = 'src/recipes/substitutions-mined.json';
const REPORT = 'runs/ingredient-normalization/ALTERNATIVES.md';

const bundled = await build({
  stdin: {
    contents: "export * from './src/recipes/alternatives-mine.ts'; export * from './src/recipes/ingredient-vocabulary.ts';",
    resolveDir: process.cwd(),
    loader: 'ts',
  },
  bundle: true, format: 'esm', platform: 'node', write: false, logLevel: 'silent',
});
const core = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);

const census = JSON.parse(readFileSync('tests/fixtures/ingredients/census-lines.json', 'utf8'));
const { pairs, orLines, usable } = core.mineAlternatives(census.rows, { vocab: core.INGREDIENT_VOCABULARY, minLines: MIN_LINES });

const report = `# Mined ingredient alternatives — review report

Generated ${new Date().toISOString().slice(0, 10)} by \`scripts/mine-alternatives.mjs\` (min-lines ${MIN_LINES}).
Census snapshot ${census.snapshot}: ${census.lines} lines, of which ${orLines} say "X or Y"; ${usable} yielded a keyed pair.

Each row is "the author uses FROM; they named USE as what they'd use instead",
directed as written, summed by line weight. These ship as SUGGESTIONS beside a
recipe line ("⇄ or: …"), never as a rewrite. **Review = read the pairs; a wrong
one is a vocabulary problem (two things folded into one key) or a genuine oddity
— drop it by adding the pair to \`_meta.dropped\` in the seed-less JSON? No:
the JSON is generated; note it here and fix the vocabulary.**

| from | use | lines |
|---|---|---:|
${pairs.map((p) => `| ${p.from} | ${p.use} | ${p.lines} |`).join('\n')}
`;
console.log(`"or" lines ${orLines}, keyed ${usable}, pairs over floor ${pairs.length}`);
console.log(pairs.slice(0, 12).map((p) => `  ${p.from} → ${p.use} (${p.lines})`).join('\n'));
if (!DRY) {
  writeFileSync(OUT, `${JSON.stringify({
    _meta: {
      why: 'Mined "X or Y" ingredient alternatives (plans/2026-08-12-1 Phase 5b). GENERATED by scripts/mine-alternatives.mjs from the census; regenerate, never hand-edit. Consumed by src/recipes/substitutions.ts as corpus-sourced suggestions.',
      generated: new Date().toISOString().slice(0, 10),
      census: { snapshot: census.snapshot, lines: census.lines, orLines, keyed: usable },
      minLines: MIN_LINES,
      pairs: pairs.length,
    },
    pairs,
  }, null, 1)}\n`);
  mkdirSync('runs/ingredient-normalization', { recursive: true });
  writeFileSync(REPORT, report);
  console.log(`wrote ${OUT} (${pairs.length} pairs) and ${REPORT}`);
}
